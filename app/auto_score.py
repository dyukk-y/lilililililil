"""Умная оценка текстовых постов для маршрутизации.

Цель: не зависеть только от точного списка фраз. Пост оценивается по
совокупности признаков: формат, намерение, обращение к человеку, username,
вопросительная форма и контекст. Стоп-слова/дубликаты/гиббериш остаются
отдельными жёсткими фильтрами.
"""
import re
from dataclasses import dataclass
from typing import List



@dataclass(frozen=True)
class AutoScore:
    score: int
    decision: str  # auto / manual
    reasons: List[str]


POSITIVE_RULES = [
    (25, re.compile(r"\bрасскажите\s+(?:про|о)\b", re.I), "запрос рассказать о человеке"),
    (24, re.compile(r"\bрасскаж(?:ите|и)\s+кто\s+(?:такой|такая)\b", re.I), "идентификация человека"),
    (22, re.compile(r"\bчто\s+за\s+(?:мальчик|девочка|парень|девушка|человек)\b", re.I), "вопрос о человеке"),
    (20, re.compile(r"\bкто\s+(?:такой|такая|он|она|это)\b", re.I), "идентификация человека"),
    (18, re.compile(r"\bкто\s+знает\b", re.I), "поиск информации о человеке"),
    (15, re.compile(r"\b(?:подскажите|расскажите|кто\s+знает)\b", re.I), "просьба сообщить информацию"),
    (15, re.compile(r"@[a-zA-Z0-9_]{3,32}\b"), "есть username"),
    (12, re.compile(r"\b(?:юз(?:ер(?:нейм)?)?|username)\b", re.I), "запрос username"),
    (12, re.compile(r"\b(?:понравил(?:ся|ась)|хочу\s+познакомиться|можно\s+познакомиться|хот(?:ел|ела)\s+познакомиться)\b", re.I), "интерес к знакомству"),
    (10, re.compile(r"\b(?:занят|занята|свободен|свободна|есть\s+(?:парень|девушка)|стоит\s+общаться)\b", re.I), "контекст отношений"),
    (8, re.compile(r"\b(?:видели|видел|видела|встретил|встретила|встречал|встречала)\b", re.I), "контекст встречи"),
    (8, re.compile(r"\b(?:в\s+центре|на\s+празднике|в\s+парке|возле\s+дк|на\s+стадионе|в\s+автобусе|в\s+школе|в\s+колледже|в\s+магазине|на\s+остановке)\b", re.I), "контекст места/события"),
    (6, re.compile(r"\b(?:кто\s+едет|кто\s+был|кто\s+идёт|кто\s+будет)\b", re.I), "вопрос сообществу"),
    (5, re.compile(r"\?\s*$"), "явный вопрос"),
]

NEGATIVE_RULES = [
    (-45, re.compile(r"\b(?:отдам|кто\s+отда[её]т|продам|куплю|продажа|купить|заказ|услуги?)\b", re.I), "купля/продажа/услуга"),
    (-40, re.compile(r"\b(?:потерял|потеряла|потеряно|наш[её]л|найден|нашли)\b", re.I), "потерянная/найденная вещь"),
    (-35, re.compile(r"\b(?:щенк|кот[её]н|кошечк|собак|котят)\w*\b", re.I), "животные/отдача"),
    (-30, re.compile(r"\b(?:карта|очки|телефон|документ|паспорт|ключи)\b", re.I), "поиск вещи/документа"),
    (-25, re.compile(r"\b(?:маникюр|ресниц|кератин|репетитор|сварк|ломбард)\w*\b", re.I), "сервисное объявление"),
]

# Слова, характерные для публикаций про конкретного человека. Они не дают
# большой прибавки сами по себе, но позволяют новым формулировкам проходить
# без точного совпадения с ключевой фразой.
PERSON_WORDS = re.compile(
    r"\b(?:мальчик|девочка|парень|девушка|мужчина|женщина|человек|" 
    r"мальчики|девочки|парни|девушки|ребята|чел|девчонка|пацан)\b", re.I
)


def score_post(text: str) -> AutoScore:
    text = (text or "").strip()
    score = 0
    reasons: List[str] = []

    # Обязательный формат начала поста даёт сильный базовый сигнал.
    if re.match(r"^(?:🧑|👩)(?:\s+или\s+(?:🧑|👩))?(?=\s|$)", text):
        score += 20
        reasons.append("правильный формат 🧑/👩")

    for points, pattern, reason in POSITIVE_RULES:
        if pattern.search(text):
            score += points
            reasons.append(f"+{points}: {reason}")

    if PERSON_WORDS.search(text):
        score += 10
        reasons.append("+10: явно упомянут человек")

    for points, pattern, reason in NEGATIVE_RULES:
        if pattern.search(text):
            score += points
            reasons.append(f"{points}: {reason}")

    # Защита от слишком коротких/непонятных сообщений. Основная проверка
    # всё равно выполняется раньше, здесь только дополнительный барьер.
    if len(text) < 12:
        score -= 15
        reasons.append("-15: слишком короткий текст")

    # Потолок/пол не нужны: итоговый балл специально остаётся прозрачным.
    decision = "auto" if score >= 60 else "manual"
    return AutoScore(score=max(-100, min(100, score)), decision=decision, reasons=reasons)
